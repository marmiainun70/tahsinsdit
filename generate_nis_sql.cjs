let sql = '-- Update NIS for students based on name matching\n\n';

const lines = rawData.trim().split('\n');

lines.forEach(line => {
  const match = line.match(/^(.*?)(\d+)$/);
  if (match) {
    const rawName = match[1].trim();
    const nis = match[2];
    
    // Create a fuzzy search pattern for ILIKE
    // e.g. "M. GILANG ARSYA" -> "%M%GILANG%ARSYA%"
    let searchPattern = rawName
      .replace(/['.]/g, '') // remove punctuation
      .split(/\s+|-/) // split by spaces or hyphens
      .map(part => part.trim())
      .filter(part => part.length > 0)
      .join('%');
      
    searchPattern = '%' + searchPattern + '%';
    
    // Escape single quotes for SQL
    const sqlSearch = searchPattern.replace(/'/g, "''");
    
    // Add safety limit so it only updates one row in case of multiple matches (optional, but good practice if not using DO block)
    // Actually PostgreSQL UPDATE doesn't have LIMIT 1, we use IN (SELECT id ... LIMIT 1)
    
    sql += `UPDATE public.students \n`;
    sql += `SET nis = '${nis}' \n`;
    sql += `WHERE id IN (\n`;
    sql += `  SELECT id FROM public.students \n`;
    sql += `  WHERE REPLACE(REPLACE(nama, '''', ''), '.', '') ILIKE '${sqlSearch}'\n`;
    sql += `  LIMIT 1\n`;
    sql += `);\n\n`;
  }
});

fs.writeFileSync('update_nis_students.sql', sql);
